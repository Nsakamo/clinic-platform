const STAFF_MEDICAL_INSTRUCTION = "スタッフが症状の説明・経過の見込み（例:『数日〜2週間ほどで落ち着きます』）・対処方法・お詫び・安心していただく言葉を指示したら、医院としての案内として、その内容と結論を弱めたり条件を付けたりせず、そのまま丁寧な文にする（上の方針の（ウ）の時は、説明を保ったうえで救急の案内を添える）。AIが指示にない新しい診断・治療判断・受診や救急の案内を加えることはしない（受診・救急の案内は上の方針の（イ）（ウ）の時を除く）。";

// 受診・救急の案内（他の医療機関へ行く・相談する・119番）に当たりそうな文
const EMERGENCY_TERMS = /119番|119(?:へ|に)(?:お電話|電話|ご連絡|連絡|通報)|(?:#|＃)7119|救急(?:車|外来|相談|窓口|病院|医療|安心|の窓口|へ|に|を)/;
const OTHER_PROVIDER = /(?:医療機関|病院|歯科医院|歯医者|歯科|診療所|クリニック|医院|医師|先生|ドクター|皮膚科|耳鼻科|耳鼻咽喉科|口腔外科|内科|眼科|お医者|他院|専門医|かかりつけ|夜間(?:・休日)?(?:の)?(?:診療|窓口)|休日診療)(?:[^。\n]{0,14}(?:受診|ご相談|相談|診察|診て|診ていただ|行って|行かれ|へ行|お越し|ご利用|ご連絡|連絡|お電話|電話|お問い合わせ)|(?:へ|に)[。！!]?$)/;
const CONDITIONAL_SEE_DOCTOR = /(?:場合|ようでしたら|ようなら|ようであれば|なければ|すぐ|早め|念のため)[^。\n]{0,12}受診(?![時前票料日])|受診を(?:ご検討|おすすめ|お勧め)|受診(?:され|して|する)[^。\n]{0,12}(?:おすすめ|お勧め)|^(?:[^。\n]{0,6}[：:])?\s*(?:念のため|早めに|一度|まずは)?[、,]?\s*受診して(?:ください|いただ)|診察を(?:お)?受け(?!ていただきます)|医師の診察を受け|救急で/;
// 提出物（証明書・診断書など）の案内と、当院への受診・来院・相談の案内は対象にしない
const SUBMISSION_CONTEXT = /証明|書類|免除|キャンセル料|受診日|領収|診断書|処方|検査結果|陽性|発行/;
const OTHER_PLACE = /お近く|他の|ほかの|別の|他院|(?:当院|当クリニック|弊院)(?:では|で)?(?:なく|対応いたしかね|対応でき)|(?:当院|当クリニック|弊院)以外|難しい場合|つかない場合/;
const OWN_CLINIC_TARGET = /(?:当院|当クリニック|当医院|弊院)(?:へ|に|で|を|まで)|(?:当院|当クリニック|弊院)の[^。\n]{0,8}(?:医師|科|スタッフ|窓口)|(?:当院|当クリニック|弊院)は医療機関|ご来院|再来院/;
function isEscalationSentence(sentence) {
  const s = String(sentence || "").normalize("NFKC");
  if (!s.trim()) return false;
  // 119番・救急は、当院や提出物への言及があっても対象にする
  if (EMERGENCY_TERMS.test(s)) return true;
  if (SUBMISSION_CONTEXT.test(s)) return false;
  // 当院への案内は対象外。ただし同じ文で他の医療機関へ促している時は対象にする
  if (OWN_CLINIC_TARGET.test(s) && !OTHER_PLACE.test(s)) return false;
  if (/医師(?:より|から|が)[^。\n]{0,12}(?:ご連絡|確認|ご説明|ご案内)|施術前に医師の診察/.test(s)) return false;
  return EMERGENCY_TERMS.test(s) || OTHER_PROVIDER.test(s) || CONDITIONAL_SEE_DOCTOR.test(s);
}

function splitSentences(text) {
  const out = [];
  for (const line of String(text || "").split("\n")) {
    const parts = line.match(/[^。！？!?]*[。！？!?]+[」』）)】]*|[^。！？!?]+$/g);
    if (parts) out.push(...parts);
  }
  return out;
}

function escalationSentences(text) {
  return Array.from(new Set(splitSentences(text).filter(isEscalationSentence).map(s => s.trim()).filter(Boolean)));
}

// 照合AIへ渡す手がかり（下書きに受診・救急の案内らしい文がある時だけ）
function escalationAuditHint(draft) {
  const found = escalationSentences(draft).slice(0, 6);
  if (!found.length) return "";
  return "\n【確認：下書きにある受診・救急の案内かもしれない文（当院への案内や、受診・救急の案内に当たらない文なら対象外）】\n" + found.map(s => "・" + s.slice(0, 200)).join("\n")
    + "\nこれらの文それぞれについて、方針の（ア）スタッフが指示した（外す指示は除く）、（イ）店舗ルールが今回の症状にその案内を明記している、（ウ）患者様の連絡に命に関わる緊急の症状がある、のどれかに当たるか確認する。どれにも当たらない文があれば pass:false、\"escalation\":true とし、reason に『スタッフの指示にない受診・救急の案内』とその文を書く。当たる場合や、当院への来院・提出物の案内、受診・救急が不要と伝える文（例:『病院へ行かれる必要はございません』）、スタッフの説明を言い換えた文であれば、この理由で不合格にしない。この確認をした照合では、JSONに必ず \"escalation\":true|false を付ける。";
}

